

/***

Subtask-1:

Display sum of all the odd numbers from 91 to 129.

 */

let sum=0;
for(let num = 91; num <= 129; num=num+2){
    sum=sum+num;
}
 console.log("sum of all the odd numbers from 91 to 129 ="+sum);


